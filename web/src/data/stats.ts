/** base โจมตีของฮีโร่ (ใช้ร่าง awake ถ้าเลือกตัว awake) · ไม่รู้ = null */
export function baseAtkOf(id: string): number | null {
  const en = englishOf(id)
  if (!en) return null
  // ชื่อในเว็บสั้นกว่าใน Atlas บางตัว เช่น "Tanjiro" = "Tanjiro Kamado"
  const row = BASE_ATK[en] ?? Object.entries(BASE_ATK).find(([k]) => k.startsWith(en + ' '))?.[1]
  if (!row) return null
  return isAwake(id) ? row[1] ?? row[0] : row[0]
}
